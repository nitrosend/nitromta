//! The reference pages in `docs/reference` show what the binary itself
//! prints and writes, so neither can drift from it.

use std::path::Path;
use std::process::Command;

fn page(name: &str) -> String {
    std::fs::read_to_string(
        Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../docs/reference")
            .join(name),
    )
    .unwrap()
}

#[test]
fn the_command_line_reference_shows_the_usage_as_printed() {
    let output = Command::new(env!("CARGO_BIN_EXE_nitromta"))
        .arg("--help")
        .output()
        .unwrap();
    assert!(output.status.success());
    let usage = String::from_utf8(output.stdout).unwrap();
    assert!(
        page("cli.md").contains(&format!("```text\n{usage}```")),
        "docs/reference/cli.md shows `nitromta --help` as it prints:\n{usage}"
    );
}

#[test]
fn the_configuration_reference_shows_what_setup_writes() {
    let dir = std::env::temp_dir().join(format!("nitromta-reference-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    let dir = std::fs::canonicalize(&dir).unwrap();
    let output = Command::new(env!("CARGO_BIN_EXE_nitromta"))
        .arg("setup")
        .arg("--config")
        .arg(dir.join("config.toml"))
        .args(["--hostname", "mta.example.com"])
        .args(["--return-path-domain", "bounces.example.com"])
        .output()
        .unwrap();
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    // As the installation guide writes it, in /etc/nitromta, with the
    // secret setup generated left out.
    let written = std::fs::read_to_string(dir.join("config.toml"))
        .unwrap()
        .replace(dir.to_str().unwrap(), "/etc/nitromta")
        .lines()
        .map(|line| {
            if line.starts_with("return_path_key = ") {
                "return_path_key = \"<64 hex digits, generated by setup>\"\n".to_owned()
            } else {
                format!("{line}\n")
            }
        })
        .collect::<String>();
    std::fs::remove_dir_all(&dir).unwrap();
    assert!(
        page("configuration.md").contains(&format!("```toml\n{written}```")),
        "docs/reference/configuration.md shows what `nitromta setup` writes:\n{written}"
    );
}
